'use client';

import React, { useEffect, useRef, useState } from 'react';

export function InlineTextField({
  value,
  onChange,
  onKeyDown,
  inputRef,
  placeholder,
  autoFocus = false,
  className = '',
}: {
  value: string;
  onChange: (event: React.ChangeEvent<HTMLInputElement>) => void;
  onKeyDown?: (event: React.KeyboardEvent<HTMLInputElement>) => void;
  inputRef?: React.RefObject<HTMLInputElement | null>;
  placeholder?: string;
  autoFocus?: boolean;
  className?: string;
}) {
  return (
    <input
      ref={inputRef}
      type="text"
      value={value}
      onChange={onChange}
      onKeyDown={onKeyDown}
      placeholder={placeholder}
      autoFocus={autoFocus}
      className={`w-full px-4 py-2 border border-gray-300 dark:border-gray-600 rounded-lg bg-white dark:bg-gray-700 text-gray-900 dark:text-white focus:ring-2 focus:ring-blue-500 focus:border-transparent ${className}`}
    />
  );
}

